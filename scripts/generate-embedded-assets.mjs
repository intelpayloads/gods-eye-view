#!/usr/bin/env node
/**
 * Generate the embeddable application's markup and scoped stylesheet.
 *
 * `index.html` stays the single source of the application chrome and
 * `style.css` (with its ordered imports) the single source of its styles. An
 * embedding host cannot own the page, so this script derives:
 *
 *   src/embedded/markup.js    APPLICATION_MARKUP = index.html <body> minus <script>,
 *                             APPLICATION_STYLESHEETS = its external <head> stylesheets
 *   src/embedded/embedded.css every rule scoped under `.gods-eye-root`
 *
 * Scoping rules: `:root`, `html` and `body` become the root element itself;
 * a leading `body.<state>` compound (the application's mode classes, toggled
 * on <body>) stays on body and scopes its remainder under the root; every
 * other selector is prefixed with `.gods-eye-root `. Keyframe steps are left
 * alone. Root-relative `url('/x.svg')` become file-relative to `public/` so a
 * bundler resolves them.
 *
 * Both outputs are committed; `src/embedded/application.test.mjs` fails when they
 * are stale. Usage: node scripts/generate-embedded-assets.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import postcss from 'postcss';

export const ROOT_CLASS = 'gods-eye-root';
const ROOT_SELECTOR = `.${ROOT_CLASS}`;
const repo = fileURLToPath(new URL('../', import.meta.url));
export const MARKUP_PATH = 'src/embedded/markup.js';
export const CSS_PATH = 'src/embedded/embedded.css';

/** The <body> content of index.html without the module entry script. */
export function extractBodyMarkup(html) {
  const open = html.match(/<body[^>]*>/i);
  const close = html.lastIndexOf('</body>');
  if (!open || close < 0) throw new Error('index.html has no <body>');
  const body = html.slice(open.index + open[0].length, close);
  return `${body.replace(/\s*<script\b[^>]*>[\s\S]*?<\/script>\s*/gi, '\n').trim()}\n`;
}

/** External stylesheets (web fonts, icon fonts) index.html loads in <head>. */
export function extractExternalStylesheets(html) {
  const head = html.slice(0, html.search(/<body[^>]*>/i));
  return [...head.matchAll(/<link\b[^>]*>/gi)]
    .map((match) => match[0])
    .filter((tag) => /\brel=["']stylesheet["']/i.test(tag))
    .map((tag) => tag.match(/\bhref=["']([^"']+)["']/i)?.[1])
    .filter((href) => href && /^https:\/\//.test(href));
}

export function renderMarkupModule(markup, stylesheets = []) {
  return [
    '// GENERATED by scripts/generate-embedded-assets.mjs from index.html. Do not edit.',
    '/** The application chrome an embedding host inserts into its root element. */',
    `export const APPLICATION_MARKUP = ${JSON.stringify(markup)};`,
    '/** External stylesheets (fonts, icon fonts) the chrome needs in <head>. */',
    `export const APPLICATION_STYLESHEETS = Object.freeze(${JSON.stringify(stylesheets)});`,
    '',
  ].join('\n');
}

/** Split a selector list on top-level commas (not inside (), [] or quotes). */
function splitTopLevel(selector, separator) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let start = 0;
  for (let i = 0; i < selector.length; i += 1) {
    const ch = selector[i];
    if (quote) {
      if (ch === '\\') i += 1;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === '(' || ch === '[') depth += 1;
    else if (ch === ')' || ch === ']') depth -= 1;
    else if (depth === 0 && separator(ch)) {
      parts.push(selector.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(selector.slice(start));
  return parts;
}

/** Length of the first compound selector (up to a top-level combinator). */
function firstCompoundLength(selector) {
  let depth = 0;
  let quote = null;
  for (let i = 0; i < selector.length; i += 1) {
    const ch = selector[i];
    if (quote) {
      if (ch === '\\') i += 1;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === '(' || ch === '[') depth += 1;
    else if (ch === ')' || ch === ']') depth -= 1;
    else if (depth === 0 && /[\s>+~]/.test(ch)) return i;
  }
  return selector.length;
}

/** Scope one complex selector under the embedding root. */
export function scopeSelector(raw) {
  const selector = raw.trim().replace(/\s+/g, ' ');
  if (!selector) return selector;
  if (selector.startsWith(ROOT_SELECTOR)) return selector;
  const length = firstCompoundLength(selector);
  const compound = selector.slice(0, length);
  const rest = selector.slice(length).trim();
  const element = compound.match(/^(:root|html|body)(?![\w-])/);
  if (!element) return `${ROOT_SELECTOR} ${selector}`;
  const state = compound.slice(element[1].length);
  if (element[1] === ':root' || !state) {
    // :root / html / body themselves are the embedding root.
    if (!rest) return ROOT_SELECTOR;
    // `html body …` scopes like `body …`.
    if (/^body(?![\w-])/.test(rest)) return scopeSelector(rest);
    return `${ROOT_SELECTOR} ${rest}`;
  }
  // body.<mode>… : the state class lives on <body>; the target lives in the root.
  return rest
    ? `${element[1]}${state} ${ROOT_SELECTOR} ${rest}`
    : `${element[1]}${state} ${ROOT_SELECTOR}`;
}

function scopeSelectorList(list) {
  return splitTopLevel(list, (ch) => ch === ',')
    .map(scopeSelector)
    .filter(Boolean)
    .join(',\n');
}

async function inlineImports(file, seen = new Set()) {
  const absolute = path.resolve(repo, file);
  if (seen.has(absolute)) return '';
  seen.add(absolute);
  const css = await readFile(absolute, 'utf8');
  const out = [];
  let last = 0;
  for (const match of css.matchAll(/@import\s+['"]([^'"]+)['"]\s*;/g)) {
    out.push(css.slice(last, match.index));
    const target = path.relative(
      repo,
      path.resolve(path.dirname(absolute), match[1]),
    );
    out.push(await inlineImports(target, seen));
    last = match.index + match[0].length;
  }
  out.push(css.slice(last));
  return out.join('');
}

export function scopeStylesheet(css, { cssPath = CSS_PATH } = {}) {
  const root = postcss.parse(css);
  const publicDir = path
    .relative(
      path.dirname(path.resolve(repo, cssPath)),
      path.join(repo, 'public'),
    )
    .split(path.sep)
    .join('/');
  root.walkRules((rule) => {
    const parent = rule.parent;
    if (parent?.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
    rule.selector = scopeSelectorList(rule.selector);
  });
  root.walkDecls((decl) => {
    if (!decl.value.includes('url(')) return;
    decl.value = decl.value.replace(
      /url\((['"]?)\/(?!\/)([^'")]+)\1\)/g,
      (_, q, file) => `url(${q}${publicDir}/${file}${q})`,
    );
  });
  const header = [
    `/* GENERATED by scripts/generate-embedded-assets.mjs from style.css. Do not edit. */`,
    `/* Every rule is scoped under ${ROOT_SELECTOR}; the host sizes and positions that element. */`,
    `${ROOT_SELECTOR} {`,
    '  position: relative;',
    '  overflow: hidden;',
    '  /* Fixed-position chrome is laid out against the root, not the host page. */',
    '  contain: layout paint;',
    '  isolation: isolate;',
    '}',
    '',
  ].join('\n');
  return `${header}${root.toString()}`;
}

export async function generateEmbeddedAssets() {
  const html = await readFile(path.join(repo, 'index.html'), 'utf8');
  const markup = renderMarkupModule(
    extractBodyMarkup(html),
    extractExternalStylesheets(html),
  );
  const css = scopeStylesheet(await inlineImports('style.css'));
  return { [MARKUP_PATH]: markup, [CSS_PATH]: css };
}

const invoked = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : '';
if (import.meta.url === invoked) {
  const check = process.argv.includes('--check');
  const outputs = await generateEmbeddedAssets();
  let stale = false;
  for (const [file, content] of Object.entries(outputs)) {
    const target = path.join(repo, file);
    const current = await readFile(target, 'utf8').catch(() => null);
    if (current === content) continue;
    if (check) {
      console.error(
        `${file} is stale; run node scripts/generate-embedded-assets.mjs`,
      );
      stale = true;
    } else {
      await writeFile(target, content);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exitCode = 1;
}
